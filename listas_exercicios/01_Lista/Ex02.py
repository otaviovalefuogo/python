# Crie duas variáveis, numero1 e numero2, e atribua a elas valores inteiros.
#  Calcule a soma, subtração, multiplicação e divisão dessas variáveis e imprima os resultados.
num1 = int(input("Digite o primeiro numero:"))
num2 = int(input("Digite o segundo número:"))
soma = num1 + num2
sub = num1 -num2
mul= num1*num2
div= num1 /num2
print(f"A soma dos numeros é {soma}")
print(f"A subtração dos numeros é {sub}")
print(f"A multiplicação dos numeros é {mul}")
print(f"A divisão dos numeros é {div}")